// Build: inline the processor source (for `pencil-voice/inline`), compile with tsc, copy the processor next to dist.
import { readFileSync, writeFileSync, copyFileSync, rmSync, mkdirSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const processor = readFileSync(`${root}src/pencil-processor.js`, "utf8");
writeFileSync(
  `${root}src/processor-source.ts`,
  `// Generated by scripts/build.mjs from pencil-processor.js. Do not edit.\nexport default ${JSON.stringify(processor)};\n`,
);
rmSync(`${root}dist`, { recursive: true, force: true });
mkdirSync(`${root}dist`);
execFileSync(process.execPath, [`${root}node_modules/typescript/bin/tsc`, "-p", root], { stdio: "inherit" });
copyFileSync(`${root}src/pencil-processor.js`, `${root}dist/pencil-processor.js`);
console.log("built dist/");
